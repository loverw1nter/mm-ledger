CREATE TABLE IF NOT EXISTS categories (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  type INTEGER NOT NULL,
  emoji TEXT NOT NULL DEFAULT '📌',
  hidden INTEGER NOT NULL DEFAULT 0,
  sort INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_categories_name_type ON categories(type, name);

CREATE TABLE IF NOT EXISTS bills (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  type INTEGER NOT NULL,
  amount_cents INTEGER NOT NULL,
  category_id INTEGER NOT NULL REFERENCES categories(id),
  date TEXT NOT NULL,
  time TEXT NOT NULL DEFAULT '12:00',
  note TEXT NOT NULL DEFAULT '',
  external_id TEXT,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX IF NOT EXISTS idx_bills_date ON bills(date);
CREATE INDEX IF NOT EXISTS idx_bills_category ON bills(category_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_bills_external ON bills(external_id) WHERE external_id IS NOT NULL;

